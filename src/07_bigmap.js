// Kollision auf der grossen Karte
G.bigSolid = (px, py) => {
  const M = G.activeMap();
  const tx = Math.floor(px / G.TILE), ty = Math.floor(py / G.TILE);
  if (tx < 0 || ty < 0 || tx >= M.W || ty >= M.H) return true;
  const ch = (M.tiles[ty] || '')[tx] || '.';
  const tile = G.TILES[ch];
  return tile ? tile.solid : false;
};

