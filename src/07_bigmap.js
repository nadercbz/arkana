// Danach ein Kanten-Pass: jede feste Kachel bekommt dort, wo sie an
// Begehbares grenzt, eine helle Oberkante und wirft einen Schlagschatten
// auf den Boden davor. Erst das macht sichtbar, wo Wand aufhoert und
// Weg anfaengt.
G.drawBigMap = (c, camX, camY, t) => {
  const M = G.activeMap(), T = G.TILE;
  const x0 = Math.max(0, Math.floor(camX / T));
  const y0 = Math.max(0, Math.floor(camY / T));
  const x1 = Math.min(M.W - 1, Math.ceil((camX + G.W) / T));
  const y1 = Math.min(M.H - 1, Math.ceil((camY + G.FIELD_H) / T));

  const at = (tx, ty) => ((M.tiles[ty] || '')[tx]) || '#';
  const solid = (tx, ty) => {
    if (tx < 0 || ty < 0 || tx >= M.W || ty >= M.H) return true;
    const tl = G.TILES[at(tx, ty)];
    return tl ? tl.solid : false;
  };

  // 1. Grundkacheln plus Dekoration auf begehbarem Boden
  for (let ty = y0; ty <= y1; ty++) {
    for (let tx = x0; tx <= x1; tx++) {
      const bio = M.biomeAt(tx, ty);
      const pal = G.BIOMES[bio] || G.pal;
      const ch = at(tx, ty);
      const x = tx * T - camX, y = ty * T - camY;
      (G.TILES[ch] || G.TILES['.']).draw(c, x, y, pal, t, tx, ty);
      // Nur auf schlichtem Boden, sonst wird es unruhig
      if (ch === '.' || ch === ',' || ch === 's' || ch === '=') {
        G.drawDeco(c, x, y, tx, ty, bio, pal, t);
      }
    }
  }

  // 2. Schlagschatten, weich auslaufend statt harte Kante.
  // Die Gradienten werden einmal gebaut und wiederverwendet.
  if (!G._shadowGrads) {
    const mk = (x0_, y0_, x1_, y1_) => {
      const g2 = c.createLinearGradient(x0_, y0_, x1_, y1_);
      g2.addColorStop(0, 'rgba(0,0,0,0.50)');
      g2.addColorStop(0.55, 'rgba(0,0,0,0.16)');
      g2.addColorStop(1, 'rgba(0,0,0,0)');
      return g2;
    };
    G._shadowGrads = {
      top: mk(0, 0, 0, 14), left: mk(0, 0, 12, 0),
      right: mk(T, 0, T - 12, 0), bottom: mk(0, T, 0, T - 10),
    };
  }
  const SG = G._shadowGrads;
  for (let ty = y0; ty <= y1; ty++) {
    for (let tx = x0; tx <= x1; tx++) {
      const tl = G.TILES[at(tx, ty)];
      if (!tl || tl.solid) continue;
      const x = tx * T - camX, y = ty * T - camY;
      c.save(); c.translate(x, y);
      if (solid(tx, ty - 1)) { c.fillStyle = SG.top; c.fillRect(0, 0, T, 14); }
      if (solid(tx - 1, ty)) { c.fillStyle = SG.left; c.fillRect(0, 0, 12, T); }
      if (solid(tx + 1, ty)) { c.fillStyle = SG.right; c.fillRect(T - 12, 0, 12, T); }
      if (solid(tx, ty + 1)) { c.fillStyle = SG.bottom; c.fillRect(0, T - 10, T, 10); }
      c.restore();
    }
  }

  // 3. Kantenlicht auf den Wänden, dort wo Begehbares angrenzt
  for (let ty = y0; ty <= y1; ty++) {
    for (let tx = x0; tx <= x1; tx++) {
      if (!solid(tx, ty)) continue;
      const pal = G.BIOMES[M.biomeAt(tx, ty)] || G.pal;
      const x = tx * T - camX, y = ty * T - camY;
      const free = (ax, ay) => !solid(ax, ay);
      // Unterkante: die zum Spieler zeigende Seite, hellster Akzent
      if (free(tx, ty + 1)) {
        c.fillStyle = pal.cardHi; c.fillRect(x, y + T - 5, T, 5);
        c.fillStyle = pal.dim; c.globalAlpha = 0.5;
        c.fillRect(x, y + T - 6, T, 1); c.globalAlpha = 1;
      }
      // Oberkante
      if (free(tx, ty - 1)) { c.fillStyle = pal.cardLight; c.fillRect(x, y, T, 3); }
      // Seiten
      if (free(tx - 1, ty)) { c.fillStyle = pal.cardLight; c.fillRect(x, y, 3, T); }
      if (free(tx + 1, ty)) { c.fillStyle = pal.cardLight; c.fillRect(x + T - 3, y, 3, T); }
      // Dunkle Trennlinie zum Boden, damit die Silhouette klar bleibt
      c.fillStyle = pal.bgVoid;
      if (free(tx, ty + 1)) c.fillRect(x, y + T - 1, T, 1);
      if (free(tx, ty - 1)) c.fillRect(x, y, T, 1);
      if (free(tx - 1, ty)) c.fillRect(x, y, 1, T);
      if (free(tx + 1, ty)) c.fillRect(x + T - 1, y, 1, T);
    }
  }
};

// Licht der sichtbaren Lichtquellen
G.drawBigLight = (c, camX, camY, t) => {
  const M = G.activeMap(), T = G.TILE;
  const L = { f: [58, 1.0], c: [50, 0.8], '*': [38, 0.6], M: [34, 0.55], p: [24, 0.35] };
  const x0 = Math.max(0, Math.floor(camX / T) - 2);
  const y0 = Math.max(0, Math.floor(camY / T) - 2);
  const x1 = Math.min(M.W - 1, Math.ceil((camX + G.W) / T) + 2);
  const y1 = Math.min(M.H - 1, Math.ceil((camY + G.FIELD_H) / T) + 2);
  c.save();
  c.globalCompositeOperation = 'lighter';
  for (let ty = y0; ty <= y1; ty++) {
    const row = M.tiles[ty] || '';
    for (let tx = x0; tx <= x1; tx++) {
      const spec = L[row[tx]];
      if (!spec) continue;
      const [r, i0] = spec;
      const x = tx * T + T / 2 - camX, y = ty * T + T / 2 - camY;
      const pal = G.BIOMES[M.biomeAt(tx, ty)] || G.pal;
      // Nachts stark, mittags fast unsichtbar
      const amb = G.dayMood().amb;
      const flick = i0 * (0.82 + 0.18 * Math.sin(t * 6 + tx * 1.7 + ty * 2.3)) * (1.25 - amb * 0.95);
      const grd = c.createRadialGradient(x, y, 0, x, y, r);
      grd.addColorStop(0, pal.glow);
      grd.addColorStop(1, 'rgba(0,0,0,0)');
      c.globalAlpha = 0.15 * flick;
      c.fillStyle = grd;
      c.fillRect(x - r, y - r, r * 2, r * 2);
    }
  }
  c.restore();
  c.globalAlpha = 1;
};


